"""Write Data/ForeverItems.lua from the Forever client's own game tables.

    python tools/make_forever_items.py <folder with ItemSparse.csv>

Butler needs two things the client may not have loaded yet: what a vendor
pays for an item, and which kind of bag a container is (quiver, ammo pouch,
soul, herb, enchanting, mining or skinning bag). Both are in the client's
ItemSparse table. This keeps only those two columns, only for items that
have them, and leaves out the items the client marks deprecated.

The tables themselves are never committed: pass the folder they were saved
in. Rerun this when Forever's build changes.
"""

import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Data", "ForeverItems.lua")

# Items the client itself marks as gone. Anything else stays: a name with
# "Old" or "Test" in it can be a real item (Old Blanchy's Feed Pouch, High
# Test Eternium Fishing Line).
def skipped(name):
    return "deprecated" in (name or "").lower()


def number(text):
    try:
        return int(text)
    except (TypeError, ValueError):
        return 0


def read(folder):
    path = os.path.join(folder, "ItemSparse.csv")
    sell, bags = {}, {}
    with open(path, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            item_id = number(row.get("ID"))
            if item_id <= 0 or skipped(row.get("Display_lang")):
                continue
            price = number(row.get("SellPrice"))
            if price > 0:
                sell[item_id] = price
            family = number(row.get("BagFamily"))
            if number(row.get("ContainerSlots")) > 0 and family > 0:
                bags[item_id] = family
    return sell, bags


def rows(table, per_line):
    keys = sorted(table)
    lines = []
    for start in range(0, len(keys), per_line):
        part = keys[start:start + per_line]
        lines.append("    " + " ".join("[%d]=%d," % (key, table[key]) for key in part))
    return "\n".join(lines)


def render(sell, bags):
    return """-- Blackthornes Butler -- Data/ForeverItems.lua
-- What the Forever client's own game tables say about items, for when the
-- client has not loaded an item yet. The live game always wins: an item's
-- tooltip and item info come first (Logic/Items.lua), and a bag's family is
-- read from the bag itself; these only fill the gap.
--
-- Generated by tools/make_forever_items.py; never edit it by hand.

local _, ns = ...

local ForeverItems = {}
ns.ForeverItems = ForeverItems

-- What a vendor pays for one, in copper, by item ID (only items it pays for).
ForeverItems.SELL = {
%s
}

-- Containers that hold only some things, by item ID: the bag family, the
-- same number the client's GetContainerNumFreeSlots gives (1 arrows,
-- 2 bullets, 4 soul shards, 32 herbs, 64 enchanting, 1024 mining, ...).
ForeverItems.BAGS = {
%s
}
""" % (rows(sell, 8), rows(bags, 6))


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    sell, bags = read(argv[1])
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(sell, bags))
    print("Wrote %d sell prices and %d bag families to Data/ForeverItems.lua" % (len(sell), len(bags)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
