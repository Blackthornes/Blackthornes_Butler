"""Write Data/QuestItems.lua: the items quests ask you to collect.

    python tools/make_quest_items.py <pfQuest folder> <folder with ItemSparse.csv>

The quest log names what a quest wants ("Murloc Eye: 3/8") but not its item
ID, and the auction house is searched by ID. So Butler ships, for each
Classic quest, the IDs of the items it collects (pfQuest's db/quests.lua,
each quest's "obj" items), kept only when the Forever client's game tables
say the item can be traded: its bonding is none, on equip or on use, never
bind on pickup or quest. Quest-only items can't be bought, so they are left
out. Forever's own quests are not in it; Butler reads their items by name.

The client tables are never committed: pass the folder they were saved in.
Rerun this when Forever's build changes.
"""

import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Data", "QuestItems.lua")

# ItemSparse's Bonding: 0 none, 1 on pickup, 2 on equip, 3 on use, 4 quest.
TRADEABLE = {0, 2, 3}


def number(text):
    try:
        return int(text)
    except (TypeError, ValueError):
        return None


def read_quests(path):
    """{ questID: [itemID, ...] } from the objective items of each quest."""
    quests = {}
    quest = None
    in_obj = False
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            top = re.match(r"^  \[(\d+)\] = \{", line)
            if top:
                quest, in_obj = int(top.group(1)), False
                continue
            if quest is None:
                continue
            if re.match(r'^    \["obj"\] = \{', line):
                in_obj = True
                continue
            if in_obj and re.match(r"^    \}", line):
                in_obj = False
                continue
            if in_obj:
                items = re.match(r'^      \["I"\] = \{([^}]*)\}', line)
                if items:
                    ids = [number(part.strip()) for part in items.group(1).split(",")]
                    quests[quest] = [i for i in ids if i]
    return quests


def read_bonding(folder):
    bonding = {}
    with open(os.path.join(folder, "ItemSparse.csv"), encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            item_id = number(row.get("ID"))
            if item_id:
                bonding[item_id] = number(row.get("Bonding")) or 0
    return bonding


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 1
    quests = read_quests(os.path.join(argv[1], "db", "quests.lua"))
    bonding = read_bonding(argv[2])
    kept = {}
    for quest, ids in quests.items():
        good = []
        for item in ids:
            if item in bonding and bonding[item] in TRADEABLE and item not in good:
                good.append(item)
        if good:
            kept[quest] = good

    lines = [
        "-- Blackthornes Butler -- Data/QuestItems.lua",
        "-- The items Classic's quests ask you to collect, by quest ID, kept only",
        "-- when they can be traded (the Forever client's game tables say how each",
        "-- binds). The quest log gives the name and the counts; this gives the ID",
        "-- the auction house is searched by (Logic/Quests.lua).",
        "--",
        "-- Generated by tools/make_quest_items.py; never edit it by hand.",
        "",
        "local _, ns = ...",
        "",
        "ns.QUEST_ITEMS = {",
    ]
    keys = sorted(kept)
    for start in range(0, len(keys), 6):
        part = keys[start:start + 6]
        lines.append("    " + " ".join(
            "[%d]={%s}," % (key, ",".join(str(i) for i in kept[key])) for key in part))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("%d quests, %d items" % (len(kept), len({i for ids in kept.values() for i in ids})))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
